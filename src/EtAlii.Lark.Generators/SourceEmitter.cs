using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace EtAlii.Lark.Generators
{
    /// <summary>Writes the generated parser for a grammar class.</summary>
    internal sealed class SourceEmitter
    {
        private const string L = "global::EtAlii.Lark.";

        private static readonly HashSet<string> ReservedNodeMembers = new()
        {
            "Tree", "Children", "RuleName", "Is", "From", "TryFrom", "Equals", "GetHashCode", "ToString", "GetType",
        };

        private readonly GrammarClassModel _model;
        private readonly string _grammar;
        private readonly GrammarModel? _grammarModel;
        private readonly Dictionary<string, string> _nodeBaseNames = new();
    private readonly Dictionary<string, string> _nodeTypeNames = new();
        private readonly StringBuilder _sb = new();
        private int _indent;

        public SourceEmitter(GrammarClassModel model, string grammar, GrammarModel? grammarModel)
        {
            _model = model;
            _grammar = grammar;
            _grammarModel = grammarModel;

            if (grammarModel is null) return;
            var used = new HashSet<string>();
            foreach (var node in grammarModel.Nodes)
            {
                var baseName = Unique(GrammarAnalyzer.ToPascalCase(node.Name), used);
                _nodeBaseNames[node.Name] = baseName;
                _nodeTypeNames[node.Name] = baseName + "Node";
            }
        }

        private void Line(string text = "")
        {
            if (text.Length > 0) _sb.Append(' ', _indent * 4).Append(text);
            _sb.Append('\n');
        }

        private void Open(string text)
        {
            Line(text);
            Line("{");
            _indent++;
        }

        private void Close(string suffix = "")
        {
            _indent--;
            Line("}" + suffix);
        }

        public string Emit()
        {
            Line("// <auto-generated/>");
            Line("#nullable enable");
            Line("#pragma warning disable CS1591, CS0108");
            Line();
            if (_model.Namespace is not null) Open($"namespace {_model.Namespace}");
            foreach (var type in _model.ContainingTypes)
            {
                Open($"partial {type.Keyword} {type.Name}");
            }

            Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"EtAlii.Lark.Generators\", \"{typeof(SourceEmitter).Assembly.GetName().Version}\")]");
            Open($"partial class {_model.ClassName}");
            EmitParser();
            if (_grammarModel is not null)
            {
                EmitNames();
                foreach (var node in _grammarModel.Nodes) EmitNode(node);
                EmitVisitor();
            }
            Close();

            foreach (var _ in _model.ContainingTypes) Close();
            if (_model.Namespace is not null) Close();
            return _sb.ToString();
        }

        private void EmitParser()
        {
            Line("/// <summary>The text of the grammar.</summary>");
            Line($"public const string GrammarText = {Verbatim(_grammar)};");
            Line();
            Line($"private static readonly global::System.Lazy<{L}Lark> s_instance = new global::System.Lazy<{L}Lark>(CreateInstance, true);");
            Line();
            Line("/// <summary>The parser of the grammar, created on first use.</summary>");
            Line($"public static {L}Lark Instance => s_instance.Value;");
            Line();
            Line("/// <summary>Implement this method to change the options of the parser.</summary>");
            Line($"static partial void ConfigureOptions({L}LarkOptions options);");
            Line();
            Open($"private static {L}Lark CreateInstance()");
            Line($"var options = new {L}LarkOptions();");
            foreach (var option in _model.Options) Line($"options.{option.Name} = {option.Expression};");
            Line("ConfigureOptions(options);");
            Line($"return new {L}Lark(GrammarText, options);");
            Close();
            Line();

            Line("/// <summary>Parses the text and returns the parse tree.</summary>");
            Line($"public static {L}Tree Parse(string text, string? start = null) => Instance.Parse(text, start);");
            Line();
            Line("/// <summary>Parses the text of the reader as it is read, and returns the parse tree.</summary>");
            Line($"public static {L}Tree Parse(global::System.IO.TextReader reader, string? start = null) => Instance.Parse(reader, start);");
            Line();
            Line("/// <summary>Parses the text of the reader asynchronously, and returns the parse tree.</summary>");
            Line($"public static global::System.Threading.Tasks.Task<{L}Tree> ParseAsync(global::System.IO.TextReader reader, string? start = null, global::System.Threading.CancellationToken cancellationToken = default) =>");
            Line("    Instance.ParseAsync(reader, start, cancellationToken);");
            Line();
            Line("/// <summary>Parses the text of the stream asynchronously, and returns the parse tree. The stream is left open.</summary>");
            Line($"public static global::System.Threading.Tasks.Task<{L}Tree> ParseAsync(global::System.IO.Stream stream, global::System.Text.Encoding? encoding = null, string? start = null, global::System.Threading.CancellationToken cancellationToken = default) =>");
            Line("    Instance.ParseAsync(stream, encoding, start, cancellationToken);");
            Line();
            Line("/// <summary>Lexes the text, without parsing it.</summary>");
            Line($"public static global::System.Collections.Generic.IEnumerable<{L}Token> Lex(string text) => Instance.Lex(text);");
            Line();
            Line("/// <summary>Lexes the text of the reader asynchronously, as it is read.</summary>");
            Line($"public static global::System.Collections.Generic.IAsyncEnumerable<{L}Token> LexAsync(global::System.IO.TextReader reader, global::System.Threading.CancellationToken cancellationToken = default) =>");
            Line("    Instance.LexAsync(reader, cancellationToken: cancellationToken);");

            foreach (var start in _model.Start)
            {
                var pascal = GrammarAnalyzer.ToPascalCase(start);
                var node = _grammarModel?.FindNode(start);
                Line();
                if (node is { IsSolid: true })
                {
                    var type = _nodeTypeNames[start];
                    Line($"/// <summary>Parses the text from the <c>{start}</c> rule.</summary>");
                    Line($"public static {type} Parse{pascal}(string text) => new {type}(Instance.Parse(text, {Literal(start)}));");
                    Line();
                    Line($"/// <summary>Parses the text of the reader asynchronously from the <c>{start}</c> rule.</summary>");
                    Line($"public static async global::System.Threading.Tasks.Task<{type}> Parse{pascal}Async(global::System.IO.TextReader reader, global::System.Threading.CancellationToken cancellationToken = default) =>");
                    Line($"    new {type}(await Instance.ParseAsync(reader, {Literal(start)}, cancellationToken).ConfigureAwait(false));");
                }
                else
                {
                    Line($"/// <summary>Parses the text from the <c>{start}</c> rule.</summary>");
                    Line($"public static {L}Tree Parse{pascal}(string text) => Instance.Parse(text, {Literal(start)});");
                    Line();
                    Line($"/// <summary>Parses the text of the reader asynchronously from the <c>{start}</c> rule.</summary>");
                    Line($"public static global::System.Threading.Tasks.Task<{L}Tree> Parse{pascal}Async(global::System.IO.TextReader reader, global::System.Threading.CancellationToken cancellationToken = default) =>");
                    Line($"    Instance.ParseAsync(reader, {Literal(start)}, cancellationToken);");
                }
            }
        }

        private void EmitNames()
        {
            Line();
            Line("/// <summary>The names of the rules and aliases of the grammar, as they appear in <see cref=\"global::EtAlii.Lark.Tree.Data\"/>.</summary>");
            Open("public static partial class Rules");
            var used = new HashSet<string>();
            foreach (var name in _grammarModel!.RuleNames.Concat(_grammarModel.Nodes.Select(n => n.Name)).Distinct())
            {
                var identifier = Unique(GrammarAnalyzer.ToPascalCase(name), used);
                Line($"public const string {identifier} = {Literal(name)};");
            }
            Close();
            Line();
            Line("/// <summary>The names of the terminals of the grammar, as they appear in <see cref=\"global::EtAlii.Lark.Token.Type\"/>.</summary>");
            Open("public static partial class Terminals");
            used.Clear();
            foreach (var name in _grammarModel.TerminalNames)
            {
                var identifier = Unique(name, used);
                Line($"public const string {identifier} = {Literal(name)};");
            }
            Close();
        }

        private void EmitNode(NodeModel node)
        {
            var type = _nodeTypeNames[node.Name];
            Line();
            Line($"/// <summary>A tree of the <c>{node.Name}</c> rule.</summary>");
            Open($"public readonly partial struct {type} : global::System.IEquatable<{type}>");
            Line("/// <summary>The data of the trees of this rule.</summary>");
            Line($"public const string RuleName = {Literal(node.Name)};");
            Line();
            Line("/// <summary>Wraps the tree.</summary>");
            Line($"/// <exception cref=\"global::System.ArgumentException\">The tree is not a <c>{node.Name}</c> tree.</exception>");
            Open($"public {type}({L}Tree tree)");
            Line("if (tree is null) throw new global::System.ArgumentNullException(nameof(tree));");
            Line($"if (tree.Data != RuleName) throw new global::System.ArgumentException($\"Expected a '{node.Name}' tree, got '{{tree.Data}}'.\", nameof(tree));");
            Line("Tree = tree;");
            Close();
            Line();
            Line("/// <summary>The wrapped tree.</summary>");
            Line($"public {L}Tree Tree {{ get; }}");
            Line();
            Line("/// <summary>The children of the tree.</summary>");
            Line("public global::System.Collections.Generic.List<object?> Children => Tree.Children;");

            if (node.Shape is not null)
            {
                foreach (var child in node.Shape)
                {
                    var name = ReservedNodeMembers.Contains(child.PropertyName) ? child.PropertyName + "Child" : child.PropertyName;
                    Line();
                    switch (child.Kind)
                    {
                        case ChildKind.Node when child.NodeName is not null && _nodeTypeNames.TryGetValue(child.NodeName, out var childType):
                            Line($"/// <summary>The <c>{child.NodeName}</c> child.</summary>");
                            Line($"public {childType} {name} => new {childType}(({L}Tree)Tree.Children[{child.Index}]!);");
                            break;
                        case ChildKind.Token:
                            Line($"/// <summary>The token at position {child.Index}.</summary>");
                            Line($"public {L}Token {name} => ({L}Token)Tree.Children[{child.Index}]!;");
                            break;
                        default:
                            Line($"/// <summary>The child at position {child.Index}: a tree or a token.</summary>");
                            Line($"public object? {name} => Tree.Children[{child.Index}];");
                            break;
                    }
                }
            }

            Line();
            Line($"/// <summary>Returns true when the value is a <c>{node.Name}</c> tree.</summary>");
            Line($"public static bool Is(object? value) => value is {L}Tree {{ Data: RuleName }};");
            Line();
            Line($"/// <summary>Wraps the value when it is a <c>{node.Name}</c> tree.</summary>");
            Open($"public static bool TryFrom(object? value, out {type} node)");
            Line($"if (value is {L}Tree {{ Data: RuleName }} tree)");
            Line("{");
            Line($"    node = new {type}(tree);");
            Line("    return true;");
            Line("}");
            Line("node = default;");
            Line("return false;");
            Close();
            Line();
            Line($"/// <summary>Wraps the value, which must be a <c>{node.Name}</c> tree.</summary>");
            Line($"public static {type} From(object? value) => new {type}(value as {L}Tree ?? throw new global::System.ArgumentException(\"Expected a tree.\", nameof(value)));");
            Line();
            Line($"public static implicit operator {L}Tree({type} node) => node.Tree;");
            Line();
            Line($"public bool Equals({type} other) => global::System.Collections.Generic.EqualityComparer<{L}Tree?>.Default.Equals(Tree, other.Tree);");
            Line();
            Line($"public override bool Equals(object? obj) => obj is {type} other && Equals(other);");
            Line();
            Line("public override int GetHashCode() => Tree?.GetHashCode() ?? 0;");
            Line();
            Line("public override string ToString() => Tree?.ToString() ?? \"\";");
            Close();
        }

        private void EmitVisitor()
        {
            Line();
            Line("/// <summary>A visitor with a method per rule. Override the methods of the rules to visit.</summary>");
            Line("/// <typeparam name=\"TResult\">The result of visiting a tree or token.</typeparam>");
            Open("public abstract partial class Visitor<TResult>");
            Line("/// <summary>Visits a tree, a token, or another value.</summary>");
            Line("public virtual TResult Visit(object? value) => value switch");
            Line("{");
            Line($"    {L}Tree tree => VisitTree(tree),");
            Line($"    {L}Token token => VisitToken(token),");
            Line("    _ => VisitOther(value),");
            Line("};");
            Line();
            Line("/// <summary>Calls the visit method of the rule of the tree.</summary>");
            Line($"public virtual TResult VisitTree({L}Tree tree) => tree.Data switch");
            Line("{");
            foreach (var node in _grammarModel!.Nodes)
            {
                Line($"    {Literal(node.Name)} => Visit{_nodeBaseNames[node.Name]}(new {_nodeTypeNames[node.Name]}(tree)),");
            }
            Line("    _ => DefaultVisit(tree),");
            Line("};");
            foreach (var node in _grammarModel.Nodes)
            {
                var type = _nodeTypeNames[node.Name];
                Line();
                Line($"/// <summary>Visits a <c>{node.Name}</c> tree. Calls <see cref=\"DefaultVisit\"/> unless overridden.</summary>");
                Line($"public virtual TResult Visit{_nodeBaseNames[node.Name]}({type} node) => DefaultVisit(node.Tree);");
            }
            Line();
            Line("/// <summary>Visits a tree whose rule has no overridden visit method. Throws unless overridden.</summary>");
            Line($"protected virtual TResult DefaultVisit({L}Tree tree) =>");
            Line("    throw new global::System.NotSupportedException($\"{GetType().Name} has no visit method for the '{tree.Data}' rule.\");");
            Line();
            Line("/// <summary>Visits a token. Throws unless overridden.</summary>");
            Line($"public virtual TResult VisitToken({L}Token token) =>");
            Line("    throw new global::System.NotSupportedException($\"{GetType().Name} has no visit method for '{token.Type}' tokens.\");");
            Line();
            Line("/// <summary>Visits a value that is neither a tree nor a token. Throws unless overridden.</summary>");
            Line("protected virtual TResult VisitOther(object? value) =>");
            Line("    throw new global::System.NotSupportedException($\"{GetType().Name} can't visit {value?.GetType().Name ?? \"null\"}.\");");
            Line();
            Line("/// <summary>Visits the children of the tree, in order.</summary>");
            Open($"protected global::System.Collections.Generic.List<TResult> VisitChildren({L}Tree tree)");
            Line("var results = new global::System.Collections.Generic.List<TResult>(tree.Children.Count);");
            Line("foreach (var child in tree.Children) results.Add(Visit(child));");
            Line("return results;");
            Close();
            Close();
        }

        private static string Unique(string identifier, HashSet<string> used)
        {
            var unique = identifier;
            for (var i = 2; !used.Add(unique); i++) unique = identifier + i;
            return unique;
        }

        private static string Literal(string value) => LarkGrammarGenerator.Literal(value);

        private static string Verbatim(string value) => "@\"" + value.Replace("\"", "\"\"") + "\"";
    }
}
