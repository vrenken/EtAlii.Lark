// Embeds the grammars that come with Lark into src/grammars.ts, so the package works without file system access.
// The grammars are the same files as the .NET and Rust packages'; CI checks that src/grammars.ts is up to date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = join(root, '..', 'dotnet', 'src', 'EtAlii.Lark', 'Grammars');
const names = ['common', 'lark', 'python', 'unicode'];
let out = '// Generated by scripts/embed-grammars.mjs from dotnet/src/EtAlii.Lark/Grammars; do not edit.\n\n';
out += '/** The grammars that come with Lark, by path. */\nexport const STANDARD_GRAMMARS: Readonly<Record<string, string>> = {\n';
for (const name of names) {
  const text = readFileSync(join(source, `${name}.lark`), 'utf8');
  out += `  'grammars/${name}.lark': ${JSON.stringify(text)},\n`;
}
out += '};\n';
writeFileSync(join(root, 'src', 'grammars.ts'), out);
